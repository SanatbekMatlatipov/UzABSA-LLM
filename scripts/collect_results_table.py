#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# =============================================================================
# UzABSA-LLM: Assemble the paper's main results table from run artifacts
# =============================================================================
"""
Reads every system's ``eval_results.json`` and emits the LaTeX body of the main
comparison table, so the manuscript's numbers are generated from the run artifacts
rather than transcribed by hand.

Also prints a plain-text v1-vs-v2 delta table when --old is supplied, which is what
the split-contamination analysis in the paper reports.

Usage:
    python scripts/collect_results_table.py --config configs/results_v2.json

Author: UzABSA Team
License: MIT
"""

import argparse
import json
from pathlib import Path

# metric path -> (row label, sub-label)
ROWS = [
    ("aspect_term_extraction.exact_match.precision",  "ATE (exact)",   "Precision"),
    ("aspect_term_extraction.exact_match.recall",     "ATE (exact)",   "Recall"),
    ("aspect_term_extraction.exact_match.f1",         "ATE (exact)",   "F1"),
    ("aspect_term_extraction.partial_match.precision","ATE (partial)", "Precision"),
    ("aspect_term_extraction.partial_match.recall",   "ATE (partial)", "Recall"),
    ("aspect_term_extraction.partial_match.f1",       "ATE (partial)", "F1"),
    ("aspect_polarity_pairs.pair_precision",          "E2E Pair",      "Precision"),
    ("aspect_polarity_pairs.pair_recall",             "E2E Pair",      "Recall"),
    ("aspect_polarity_pairs.pair_f1",                 "E2E Pair",      "F1"),
    ("aspect_polarity_pairs.sentiment_accuracy",      "Sentiment",     "Accuracy"),
    ("aspect_polarity_pairs.sentiment_macro_f1",      "Sentiment",     "Macro-F1"),
    ("json_parse_rate",                               "JSON parse",    "Success rate"),
]


def dig(d, path):
    for k in path.split("."):
        if not isinstance(d, dict) or k not in d:
            return None
        d = d[k]
    return d


def load(spec):
    """spec: {name, results} where results is a path to an eval_results*.json"""
    p = Path(spec["results"])
    if p.is_dir():
        cands = sorted(p.glob("eval_results*.json"))
        if not cands:
            raise FileNotFoundError(f"no eval_results*.json in {p}")
        p = cands[-1]
    return json.loads(p.read_text(encoding="utf-8"))


def fmt(v, label):
    if v is None:
        return "---"
    if label == "JSON parse":
        return f"{v:.1f}" + r"\%"
    return f"{v:.4f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True,
                    help="JSON: {'systems':[{'name','results'}], 'old':[{'name','results'}]}")
    ap.add_argument("--out", default=None, help="write the LaTeX rows here")
    args = ap.parse_args()

    cfg = json.loads(Path(args.config).read_text(encoding="utf-8"))
    systems = cfg["systems"]
    data = [load(s) for s in systems]

    lines = []
    prev_group = None
    for path, group, sub in ROWS:
        vals = [dig(d, path) for d in data]
        present = [v for v in vals if v is not None]
        if not present:
            continue
        best = max(present)
        cells = []
        for v in vals:
            c = fmt(v, group)
            if v is not None and abs(v - best) < 1e-12:
                c = rf"\textbf{{{c}}}"
            cells.append(c)
        if group != prev_group and prev_group is not None:
            lines.append(r"\midrule")
        n_sub = sum(1 for _, g, _ in ROWS if g == group)
        if group != prev_group and n_sub > 1:
            lines.append(rf"\multirow{{{n_sub}}}{{*}}{{{group}}}")
            lead = "  "
        elif group != prev_group:
            lead = f"{group} "
        else:
            lead = "  "
        lines.append(f"{lead}& {sub:<12} & " + " & ".join(cells) + " \\\\")
        prev_group = group

    latex = "\n".join(lines)
    print("% ---- generated by scripts/collect_results_table.py ----")
    print("% columns: " + " | ".join(s["name"] for s in systems))
    print(latex)

    if "old" in cfg:
        print("\n\n=== v1 (contaminated split) vs v2 (deduplicated split) ===")
        old = {s["name"]: load(s) for s in cfg["old"]}
        keys = ["aspect_term_extraction.exact_match.f1",
                "aspect_term_extraction.partial_match.f1",
                "aspect_polarity_pairs.pair_f1",
                "aspect_polarity_pairs.sentiment_accuracy",
                "aspect_polarity_pairs.sentiment_macro_f1"]
        hdr = ["ATEex", "ATEpa", "PairF1", "SentAcc", "SentMF1"]
        print(f"{'system':22s} " + " ".join(f"{h:>8}" for h in hdr))
        for s, d in zip(systems, data):
            if s["name"] not in old:
                continue
            o = old[s["name"]]
            nv = [dig(d, k) for k in keys]
            ov = [dig(o, k) for k in keys]
            print(f"{s['name']:22s} " + " ".join(f"{x:8.4f}" if x is not None else "     ---" for x in ov) + "   (v1)")
            print(f"{'':22s} " + " ".join(f"{x:8.4f}" if x is not None else "     ---" for x in nv) + "   (v2)")
            print(f"{'':22s} " + " ".join(
                f"{b-a:+8.4f}" if (a is not None and b is not None) else "     ---"
                for a, b in zip(ov, nv)) + "   (delta)")

    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(latex + "\n", encoding="utf-8")
        print(f"\nSaved LaTeX rows -> {args.out}")


if __name__ == "__main__":
    main()
